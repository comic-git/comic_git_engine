import json
import logging
import os
import re
from collections.abc import Iterable, Mapping
from configparser import RawConfigParser
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlparse

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from build.content import content_paths
from build.content.page_sources import load_page_source_from_toml, parse_iso_post_date
from core.models import ComicBuildResult


CMS_SECTION = "CMS"
DEFAULT_BRANCH = "master"
DEFAULT_AUTH_ENDPOINT = "auth"
REPOSITORY_PATTERN = re.compile(r"^[^/\s]+/[^/\s]+$")
GENERATED_FILE_MARKER = "Generated by comic_git_engine. Do not edit."
DECAP_CMS_VERSION = "3.16.0"
DECAP_CMS_URL = f"https://unpkg.com/decap-cms@{DECAP_CMS_VERSION}/dist/decap-cms.js"
CMS_TEMPLATE_ROOT = Path(__file__).resolve().parents[3] / "templates" / "cms"
CMS_TEMPLATE_ENVIRONMENT = Environment(
    loader=FileSystemLoader(CMS_TEMPLATE_ROOT),
    undefined=StrictUndefined,
    keep_trailing_newline=True,
)

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class CmsSettings:
    enabled: bool
    repository: str | None = None
    branch: str = DEFAULT_BRANCH
    backend_base_url: str | None = None
    backend_auth_endpoint: str = DEFAULT_AUTH_ENDPOINT
    editorial_workflow: bool = False
    local_backend: bool = False


@dataclass(frozen=True)
class CmsCollection:
    name: str
    label: str
    folder: str


class CmsReadinessError(ValueError):
    def __init__(self, problems: list[str]):
        self.problems = tuple(problems)
        super().__init__(
            "The CMS cannot safely edit every comic page yet:\n- " + "\n- ".join(problems)
        )


def render_admin_index() -> str:
    template = CMS_TEMPLATE_ENVIRONMENT.get_template("index.html")
    return template.render(decap_cms_url=DECAP_CMS_URL)


def build_cms_collections(comic_results: Iterable[ComicBuildResult]) -> list[CmsCollection]:
    results = list(comic_results)
    main_results = [result for result in results if not result.comic_folder.strip("/\\")]
    if len(main_results) != 1:
        raise ValueError("Expected exactly one main comic when generating the CMS configuration.")

    collections = [
        CmsCollection(
            name="main_comic_pages",
            label="Main Comic Pages",
            folder="your_content/comics",
        )
    ]
    extras = [result for result in results if result.comic_folder.strip("/\\")]
    for ordinal, result in enumerate(extras, start=1):
        comic_folder = _normalize_comic_folder(result.comic_folder)
        suffix = re.sub(r"[^a-z0-9]+", "_", comic_folder.casefold()).strip("_") or "comic"
        comic_name = result.comic_info.get(
            "Comic Info",
            "Comic name",
            fallback=comic_folder,
        ).strip() or comic_folder
        collections.append(
            CmsCollection(
                name=f"extra_comic_{ordinal}_{suffix}",
                label=f"{comic_name} Pages",
                folder=f"your_content/{comic_folder}/comics",
            )
        )
    return collections


def render_admin_config(settings: CmsSettings, collections: list[CmsCollection]) -> str:
    if not settings.enabled:
        raise ValueError("Cannot render an admin configuration while the CMS is disabled.")
    if not collections:
        raise ValueError("Cannot render an admin configuration without a comic collection.")

    template = CMS_TEMPLATE_ENVIRONMENT.get_template("config.yml.tpl")
    return template.render(
        backend=_render_backend(settings),
        publish_mode="publish_mode: editorial_workflow\n" if settings.editorial_workflow else "",
        collections="\n".join(_render_collection(collection) for collection in collections),
    )


def write_cms_admin(
        settings: CmsSettings,
        collections: list[CmsCollection],
        output_dir: str,
) -> None:
    if not settings.enabled:
        if not output_dir:
            from build.output.site_output import remove_generated_cms_files
            remove_generated_cms_files()
        return

    validate_cms_page_roots([collection.folder for collection in collections])
    rendered_files = {
        "index.html": render_admin_index(),
        "config.yml": render_admin_config(settings, collections),
    }
    output_root = output_dir or "."
    admin_dir = os.path.join(output_root, "admin")
    os.makedirs(admin_dir, exist_ok=True)
    for filename, content in rendered_files.items():
        path = os.path.join(admin_dir, filename)
        if os.path.exists(path):
            logger.warning("Overwriting output file with engine-generated CMS file: %s", path)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)


def _render_backend(settings: CmsSettings) -> str:
    if settings.local_backend:
        return "backend:\n  name: git-gateway\nlocal_backend: true"
    return "\n".join((
        "backend:",
        "  name: github",
        f"  repo: {_yaml_string(settings.repository or '')}",
        f"  branch: {_yaml_string(settings.branch)}",
        f"  base_url: {_yaml_string(settings.backend_base_url or '')}",
        f"  auth_endpoint: {_yaml_string(settings.backend_auth_endpoint)}",
    ))


def _render_collection(collection: CmsCollection) -> str:
    template = CMS_TEMPLATE_ENVIRONMENT.get_template("collection.yml.tpl")
    return template.render(collection=collection).rstrip("\n")


def _yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _normalize_comic_folder(value: str) -> str:
    if not isinstance(value, str) or not value.strip() or value.startswith(("/", "\\")):
        raise ValueError(f"Invalid Extra Comic path for CMS generation: {value!r}")
    normalized = value.replace("\\", "/").strip("/")
    if any(part in ("", ".", "..") for part in normalized.split("/")):
        raise ValueError(f"Invalid Extra Comic path for CMS generation: {value!r}")
    return normalized


def resolve_cms_settings(
        comic_info: RawConfigParser,
        *,
        source_is_toml: bool,
        local_backend: bool = False,
        environ: Mapping[str, str] | None = None,
) -> CmsSettings:
    enabled = _get_boolean(comic_info, "Enabled", fallback=False)
    if not enabled:
        return CmsSettings(enabled=False)

    if not source_is_toml:
        raise ValueError(
            "The CMS can only be enabled from your_content/comic_info.toml. "
            "Migrate the main comic configuration from comic_info.ini before enabling it."
        )

    branch = comic_info.get(CMS_SECTION, "Branch", fallback=DEFAULT_BRANCH).strip()
    if not branch:
        raise ValueError("Invalid [cms] branch: expected a nonblank branch name.")

    auth_endpoint = comic_info.get(
        CMS_SECTION,
        "Backend auth endpoint",
        fallback=DEFAULT_AUTH_ENDPOINT,
    ).strip()
    if not _is_relative_endpoint(auth_endpoint):
        raise ValueError(
            "Invalid [cms] backend_auth_endpoint: expected a nonblank relative path such as 'auth'."
        )

    editorial_workflow = _get_boolean(comic_info, "Editorial workflow", fallback=False)
    if local_backend and editorial_workflow:
        raise ValueError(
            "The Decap local backend does not support editorial workflow. "
            "Set cms.editorial_workflow to false while testing locally."
        )

    if local_backend:
        return CmsSettings(
            enabled=True,
            branch=branch,
            backend_auth_endpoint=auth_endpoint,
            editorial_workflow=False,
            local_backend=True,
        )

    environment = os.environ if environ is None else environ
    repository = comic_info.get(CMS_SECTION, "Repository", fallback="").strip()
    if not repository:
        repository = environment.get("GITHUB_REPOSITORY", "").strip()
    if not REPOSITORY_PATTERN.fullmatch(repository):
        raise ValueError(
            "Invalid [cms] repository: expected 'owner/repository' in comic_info.toml "
            "or GITHUB_REPOSITORY."
        )

    backend_base_url = comic_info.get(CMS_SECTION, "Backend base URL", fallback="").strip()
    if not _is_valid_backend_url(backend_base_url):
        raise ValueError(
            "Invalid [cms] backend_base_url: expected an absolute HTTPS URL "
            "(HTTP is allowed only for localhost testing)."
        )

    return CmsSettings(
        enabled=True,
        repository=repository,
        branch=branch,
        backend_base_url=backend_base_url,
        backend_auth_endpoint=auth_endpoint,
        editorial_workflow=editorial_workflow,
    )


def validate_cms_page_roots(page_roots: list[str]) -> None:
    problems = []
    for page_root in page_roots:
        try:
            entries = sorted(os.scandir(page_root), key=lambda entry: entry.name.casefold())
        except FileNotFoundError:
            continue
        except OSError as e:
            problems.append(f"{page_root}: could not inspect the comics folder ({e}).")
            continue
        for entry in entries:
            if entry.is_dir():
                problems.extend(_get_page_readiness_problems(entry.path))
    if problems:
        raise CmsReadinessError(problems)


def _get_page_readiness_problems(page_path: str) -> list[str]:
    toml_path, ini_path = content_paths.get_page_info_candidates(page_path)
    if not os.path.isfile(toml_path):
        if os.path.isfile(ini_path):
            return [f"{ini_path}: migrate this page from info.ini to info.toml."]
        return [f"{page_path}: add an info.toml file before managing this folder with the CMS."]

    try:
        source = load_page_source_from_toml(toml_path)
    except (OSError, ValueError, KeyError) as e:
        return [f"{toml_path}: fix the invalid page configuration ({e})."]

    problems = []
    if source.title is None or not source.title.strip():
        problems.append(f"{toml_path}: add a nonblank title for CMS editing.")

    try:
        parsed_post_date = parse_iso_post_date(source.post_date)
    except ValueError:
        parsed_post_date = None
    if parsed_post_date is None or hasattr(parsed_post_date, "hour"):
        problems.append(
            f"{toml_path}: use a date-only post_date such as 2026-09-05; "
            "timestamp editing is not supported yet."
        )

    unsupported_values = {
        "transcripts": source.transcripts,
        "social_media": source.social_media,
        "extra": source.extra,
    }
    for table_name, value in unsupported_values.items():
        if value:
            problems.append(
                f"{toml_path}: remove or manually manage the nonempty [{table_name}] table; "
                "the first CMS editor cannot preserve it yet."
            )
    return problems


def _get_boolean(comic_info: RawConfigParser, option: str, *, fallback: bool) -> bool:
    try:
        return comic_info.getboolean(CMS_SECTION, option, fallback=fallback)
    except ValueError as e:
        toml_key = option.lower().replace(" ", "_")
        raise ValueError(f"Invalid [cms] {toml_key}: expected true or false.") from e


def _is_relative_endpoint(value: str) -> bool:
    if not value or value.startswith(("/", "\\")):
        return False
    parsed = urlparse(value)
    return not parsed.scheme and not parsed.netloc and not parsed.query and not parsed.fragment


def _is_valid_backend_url(value: str) -> bool:
    if not value:
        return False
    parsed = urlparse(value)
    if not parsed.netloc or parsed.username or parsed.password or parsed.params or parsed.query or parsed.fragment:
        return False
    if parsed.scheme == "https":
        return True
    return parsed.scheme == "http" and parsed.hostname in {"localhost", "127.0.0.1", "::1"}
